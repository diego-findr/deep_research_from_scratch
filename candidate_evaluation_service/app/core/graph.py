# ===== STATE DEFINITIONS =====

class CandidateEvaluationState(TypedDict):
    """State for the multi-agent candidate evaluation pipeline."""
    # Input data
    enriched_candidate: Dict[str, Any]
    enriched_job: Dict[str, Any]
    
    # Agent evaluations (appended by each agent)
    agent_evaluations: Annotated[List[Dict[str, Any]], operator.add]
    
    # Debate phase (messages between agents)
    debate_messages: Annotated[List[Dict[str, Any]], operator.add]
    
    # Questions generated by agents
    questions_asked: Annotated[List[Dict[str, Any]], operator.add]
    
    # Final consensus decision
    consensus_decision: Optional[Dict[str, Any]]
    
    # Complete reasoning log for explainability
    reasoning_log: Annotated[List[Dict[str, Any]], operator.add]
    
    # Control flags
    debate_round: int
    max_debate_rounds: int
    
    # Gatekeeper decision
    gatekeeper_decision: Optional[Dict[str, Any]]


# ===== UTILITY FUNCTIONS =====

def get_model():
    """Get the configured chat model."""
    return init_chat_model(model=settings.MODEL_NAME)

def get_sector_from_job(enriched_job: Dict[str, Any]) -> str:
    """Extract the primary sector from enriched job data."""
    if 'identity' in enriched_job:
        sector = enriched_job['identity'].get('sector')
        if sector:
            return sector
    
    semantic = enriched_job.get("semantic_enrichment", {})
    analysis = semantic.get("analysis_components", {})
    sector_info = analysis.get("sector_inference", {})
    return sector_info.get("primary_sector", "unknown")


def get_candidate_name(enriched_candidate: Dict[str, Any]) -> str:
    """Extract candidate name from enriched data."""
    identity = enriched_candidate.get("identity", {})
    return identity.get("full_name", "Unknown Candidate")


def get_job_title(enriched_job: Dict[str, Any]) -> str:
    """Extract job title from enriched data."""
    if 'identity' in enriched_job:
        title = enriched_job['identity'].get('title')
        if title:
            return title
    
    raw_job = enriched_job.get("raw_job_posting", {})
    return raw_job.get("job_title", "Unknown Role")


def add_reasoning_log(
    state: CandidateEvaluationState,
    step: str,
    agent: str | None,
    action: str,
    input_summary: str,
    output_summary: str,
    key_insights: List[str] = None,
) -> Dict[str, Any]:
    """Add an entry to the reasoning log."""
    entry = ReasoningLogEntry(
        step=step,
        agent=agent,
        action=action,
        input_summary=input_summary,
        output_summary=output_summary,
        key_insights=key_insights or [],
    )
    return {"reasoning_log": [entry.model_dump()]}


# ===== AGENT NODES =====

def evaluate_gatekeeper(state: CandidateEvaluationState) -> Dict[str, Any]:
    """Gatekeeper Agent Node."""
    logger.info("[agent]🛡️ Gatekeeper Agent analyzing candidate...[/agent]")
    model = get_model()
    sector = get_sector_from_job(state["enriched_job"])
    
    prompt = GATEKEEPER_EVALUATOR_PROMPT.format(
        enriched_candidate=format_enriched_data(state["enriched_candidate"]),
        enriched_job=format_enriched_data(state["enriched_job"]),
    )
    
    structured_llm = model.with_structured_output(GatekeeperDecision)
    response = structured_llm.invoke([HumanMessage(content=prompt)])
    decision = response.model_dump()
    
    if decision['proceed']:
        logger.info(f"[success]✅ Gatekeeper Approved[/success] (Confidence: {decision['confidence']:.2f})")
    else:
        logger.info(f"[error]⛔ Gatekeeper Rejected[/error] (Confidence: {decision['confidence']:.2f})")
        logger.info(f"   Reasons: {', '.join(decision['knockout_reasons'])}")
    
    log_entry = add_reasoning_log(
        state,
        step="gatekeeper_evaluation",
        agent="gatekeeper",
        action="Performed initial knockout assessment",
        input_summary=f"Candidate vs Job in {sector}",
        output_summary=f"Proceed: {decision['proceed']}, Reasons: {decision['knockout_reasons']}",
        key_insights=[decision['reasoning']],
    )
    
    return {
        "gatekeeper_decision": decision,
        **log_entry,
    }


def fast_reject(state: CandidateEvaluationState) -> Dict[str, Any]:
    """Fast Reject Node."""
    logger.warning("[warning]⛔ Fast Reject triggered. Skipping full evaluation.[/warning]")
    gatekeeper_decision = state["gatekeeper_decision"]
    
    consensus = ConsensusDecision(
        liked=False,
        overall_score=0.0,
        decision_confidence=gatekeeper_decision["confidence"],
        primary_reasons=gatekeeper_decision["knockout_reasons"],
        consensus_summary=f"Candidate was rejected by Gatekeeper due to critical mismatches: {gatekeeper_decision['reasoning']}",
        agent_agreements=[],
        key_strengths=[],
        key_concerns=gatekeeper_decision["knockout_reasons"],
        suggested_next_steps=["Do not proceed."],
        compatibility_breakdown=[],
    )
    
    log_entry = add_reasoning_log(
        state,
        step="fast_reject",
        agent="system",
        action="Generated fast rejection based on Gatekeeper",
        input_summary="Gatekeeper knockout",
        output_summary="Decision: False (Fast Reject)",
        key_insights=gatekeeper_decision["knockout_reasons"],
    )
    
    return {
        "consensus_decision": consensus.model_dump(),
        **log_entry,
    }


